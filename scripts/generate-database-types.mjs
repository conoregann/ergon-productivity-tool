import { readFile, writeFile, readdir } from 'node:fs/promises'
import { PGlite } from '@electric-sql/pglite'

// Generates scalar table types from the migrations without requiring Docker.
// Switch to `supabase gen types typescript --local` when adding joined queries.
const db = new PGlite()
try {
  await db.exec(`
    create role anon;
    create role authenticated;
    create schema auth;
    create table auth.users (id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;
  `)
  for (const name of (await readdir('supabase/migrations'))
    .filter((name) => name.endsWith('.sql'))
    .sort()) {
    await db.exec(await readFile(`supabase/migrations/${name}`, 'utf8'))
  }
  const { rows } = await db.query(`
    select table_name, column_name, data_type, is_nullable, column_default
    from information_schema.columns where table_schema = 'public'
    order by table_name, ordinal_position
  `)
  const typeMap = {
    uuid: 'string',
    text: 'string',
    date: 'string',
    'timestamp with time zone': 'string',
    integer: 'number',
    bigint: 'number',
  }
  const tables = Map.groupBy(rows, (row) => row.table_name)
  let output =
    '// Generated by npm run db:types from versioned SQL migrations. Do not edit.\n'
  output += 'export type Database = { public: { Tables: {\n'
  for (const [table, columns] of tables) {
    output += `${table}: {\n`
    for (const operation of ['Row', 'Insert', 'Update']) {
      output += `${operation}: {\n`
      for (const column of columns) {
        const scalar = typeMap[column.data_type]
        if (!scalar) throw new Error(`Unsupported type: ${column.data_type}`)
        const nullable = column.is_nullable === 'YES'
        const optional =
          operation === 'Update' ||
          (operation === 'Insert' &&
            (nullable || column.column_default !== null))
        output += `${column.column_name}${optional ? '?' : ''}: ${scalar}${nullable ? ' | null' : ''}\n`
      }
      output += '}\n'
    }
    output += 'Relationships: []\n}\n'
  }
  output +=
    '}; Views: { [_ in never]: never }; Functions: { [_ in never]: never }; Enums: { [_ in never]: never }; CompositeTypes: { [_ in never]: never } } }\n'
  await writeFile('src/lib/database.types.ts', output)
} finally {
  await db.close()
}
